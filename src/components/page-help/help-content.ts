export function helpForPath(pathname: string): PageHelp | undefined {
  const path = pathname.length > 1 ? pathname.replace(/\/+$/, '') : pathname
  return PAGE_HELP[path.replace(/^\/flights\/[^/]+$/, '/flights/$flightId')]
}
